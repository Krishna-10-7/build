import { createHash } from 'node:crypto';
import type { Contract, Criterion, Expect, Step } from '@sentinelqa/core';

/**
 * Specs are written from templates, never by the LLM. They refer to elements by
 * key, so a heal changes locators.json and the spec bytes stay identical.
 */

const q = (s: string) => JSON.stringify(s);

function stepLine(s: Step): string {
  switch (s.do) {
    case 'goto':
      return `await page.goto(${q(s.url)});`;
    case 'click':
      return `await loc(page, ${q(s.key)}).click();`;
    case 'fill':
      return `await loc(page, ${q(s.key)}).fill(${q(s.value)});`;
  }
}

function expectLine(e: Expect): string {
  const tag = `// @criterion ${e.id}`;
  switch (e.type) {
    case 'text':
      return e.equals !== undefined
        ? `${tag}\n    await expect(loc(page, ${q(e.key)})).toHaveText(${q(e.equals)});`
        : `${tag}\n    await expect(loc(page, ${q(e.key)})).toContainText(${q(e.contains ?? '')});`;
    case 'visible':
      return `${tag}\n    await expect(loc(page, ${q(e.key)})).toBeVisible();`;
    case 'request':
      return `${tag}\n    expect(seen.some((r) => r.method === ${q(e.method)} && r.path === ${q(e.path)} && r.status === ${e.status})).toBe(true);`;
    case 'url':
      return `${tag}\n    await expect(page).toHaveURL((u) => u.pathname === ${q(e.path)});`;
  }
}

function testBlock(ticket: string, c: Criterion): string {
  const needsTraffic = c.expect.some((e) => e.type === 'request');
  const body = [
    ...(needsTraffic ? ['const seen = track(page);'] : []),
    ...c.steps.map(stepLine),
    ...c.expect.map(expectLine),
  ];
  return `  test(${q(`${ticket} ${c.id}: ${c.text}`)}, { annotation: { type: 'criterion', description: ${q(`${ticket}/${c.id}`)} } }, async ({ page }) => {
    ${body.join('\n    ')}
  });`;
}

export function generateSpec(contract: Contract): string {
  const tests = contract.criteria.filter((c) => c.testable).map((c) => testBlock(contract.ticket, c));
  const skipped = contract.criteria
    .filter((c) => !c.testable)
    .map((c) => `  test.skip(${q(`${contract.ticket} ${c.id}: ${c.text}`)}, () => {}); // ${c.note ?? 'not testable'}`);
  return `// Generated by SentinelQA from ${contract.ticket}. Do not edit by hand:
// runs refuse a spec whose hash no longer matches spec.lock.json.
import { test, expect } from '@playwright/test';
import { loc, track } from './loc';

test.describe(${q(`${contract.ticket} ${contract.title}`)}, () => {
${[...tests, ...skipped].join('\n\n')}
});
`;
}

/** Helper the generated spec imports. Reads locators.json, the only file a heal may change. */
export const LOC_HELPER = `import { readFileSync } from 'node:fs';
import type { Locator, Page } from '@playwright/test';

type Entry =
  | { strategy: 'testid'; value: string }
  | { strategy: 'role'; role: string; name: string }
  | { strategy: 'label'; name: string }
  | { strategy: 'id'; value: string }
  | { strategy: 'css'; selector: string };

const map: Record<string, Entry> = JSON.parse(readFileSync(new URL('./locators.json', import.meta.url), 'utf8'));

export function loc(page: Page, key: string): Locator {
  const e = map[key];
  if (!e) throw new Error('no locator for ' + key);
  switch (e.strategy) {
    case 'testid': return page.getByTestId(e.value);
    case 'role': return page.getByRole(e.role as Parameters<Page['getByRole']>[0], { name: e.name, exact: true });
    case 'label': return page.getByLabel(e.name, { exact: true });
    case 'id': return page.locator('[id="' + e.value + '"]');
    case 'css': return page.locator(e.selector);
  }
}

export function track(page: Page): { method: string; path: string; status: number }[] {
  const seen: { method: string; path: string; status: number }[] = [];
  page.on('response', (r) => seen.push({ method: r.request().method(), path: new URL(r.url()).pathname, status: r.status() }));
  return seen;
}
`;

